"""
Build docs/paper/references.bib from research_papers/README.md - the ONLY allowed source.

Why generated and not hand-written: the library metadata was verified against the arXiv
API (several web summaries had wrong venues). A bib typed from memory - by a person or a
model - reintroduces exactly those errors, and AI models invent plausible papers. So the
bib is a build product: change the library, re-run this, never edit references.bib.

Cite keys are the library IDs: \cite{D01}, \cite{R02}, ...
Entries whose metadata is ambiguous in the library get a "% VERIFY:" comment and an
`x_verify` field; docs/paper/check_paper.py refuses a draft that cites one of them until
a human has checked it and removed the flag in research_papers/README.md.

  conda run -n robosketch --no-capture-output python docs/paper/make_bib.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "research_papers", "README.md")
OUT = os.path.join(ROOT, "docs", "paper", "references.bib")

CONF = ["ICRA", "IROS", "ICML", "ICLR", "NeurIPS", "ICCV", "RSS", "BMVC", "WAFR",
        "SSCI", "SIGGRAPH", "Computational Aesthetics"]
JOURNAL = ["JMLR", "IJRR", "Transactions", "TOG"]


def entries(text):
    blocks = re.split(r"^### ", text, flags=re.M)[1:]
    for b in blocks:
        m = re.match(r"([FDAVR]\d{2}) — (.+)", b)
        if not m:
            continue
        key = m.group(1)
        title = re.sub(r"★\s*#\d+", "", m.group(2))
        title = re.sub(r"[^\w\s:,\-\(\)\.'&/+]", "", title).strip()
        au = re.search(r"\*\*Authors:\*\*\s*(.+)", b)
        yv = re.search(r"\*\*Year / venue:\*\*\s*(.+)", b)
        yield key, title, (au.group(1).strip() if au else ""), (yv.group(1).strip() if yv else "")


def bib(key, title, authors, yv):
    verify = []
    yv = yv.replace("**", "")
    authors = re.sub(r"\s*\([^)]*\)\s*$", "", authors).strip()      # drop "(affiliation)"
    if not authors or "see PDF" in authors or authors.startswith("("):
        verify.append("authors missing in library")
        authors = ""
    names = " and ".join(a.strip() for a in authors.split(",") if a.strip())
    years = re.findall(r"\b(19|20)(\d{2})\b", re.sub(r"arXiv:\S+", "", yv))
    years = ["".join(y) for y in years]
    arxiv = re.search(r"arXiv:(\d{4}\.\d{4,5})", yv)
    parts = [p.strip() for p in yv.split("·")]
    venue = parts[1] if len(parts) > 1 and not parts[1].startswith("arXiv") else ""
    venue = re.sub(r"\s*\(.*?\)", "", venue).strip()
    # A published paper is cited by its VENUE year (ICRA 2023), not its arXiv year. The
    # leading field may span two years ("2022/2023"); that is fine if the venue year is one
    # of them. A venue year outside the leading field is a real inconsistency -> VERIFY.
    lead = re.findall(r"\b(?:19|20)\d{2}\b", parts[0]) if parts else []
    vyear = re.findall(r"\b(?:19|20)\d{2}\b", venue)
    if vyear:
        year = vyear[0]
        if lead and year not in lead:
            verify.append("venue year %s not in year field %s" % (year, parts[0]))
    else:
        year = years[0] if years else ""
        if len(set(lead)) > 1:
            verify.append("year ambiguous: " + yv)

    fields = {"title": "{" + title + "}", "author": names, "year": year,
              "note": "library: " + key}
    if arxiv:
        fields["eprint"] = arxiv.group(1)
        fields["archivePrefix"] = "arXiv"
    if any(c in venue for c in CONF):
        kind = "inproceedings"
        fields["booktitle"] = venue
    elif any(j in venue for j in JOURNAL):
        kind = "article"
        fields["journal"] = venue
    else:
        kind = "misc"
        if arxiv:
            fields["howpublished"] = "arXiv preprint arXiv:" + arxiv.group(1)
    if verify:
        fields["x_verify"] = "; ".join(verify)

    lines = []
    if verify:
        lines.append("% VERIFY: " + "; ".join(verify))
    lines.append("@%s{%s," % (kind, key))
    for k, v in fields.items():
        lines.append("  %s = {%s}," % (k, v))
    lines.append("}")
    return "\n".join(lines), bool(verify)


def main():
    text = open(SRC, encoding="utf-8").read()
    out, n, nv = [], 0, 0
    out.append("% GENERATED by docs/paper/make_bib.py from research_papers/README.md.")
    out.append("% DO NOT EDIT BY HAND. Do not add entries here - add them to the library.")
    out.append("% e-David = A09 (Deussen et al., CAe 2012), added to the library 2026-11-08.\n")
    for key, title, authors, yv in entries(text):
        b, v = bib(key, title, authors, yv)
        out.append(b + "\n")
        n += 1
        nv += v
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {OUT}: {n} entries, {nv} flagged VERIFY")


if __name__ == "__main__":
    main()
